def _readme(items: list[dict]) -> str:
    by_cat: dict[str, list[dict]] = {}
    for it in items:
        by_cat.setdefault(it["category"], []).append(it)
    lines = [
        "# resolve-assist asset library",
        "",
        "Royalty-free assets generated on your Mac by resolve-assist. " + LICENSE,
        "",
        "## Use it in DaVinci Resolve",
        "1. Media page (or Edit page Media Pool) → right-click → **Import Media…** → select files from this folder.",
        "   Or drag the whole `library` folder into the Media Pool (keeps the subfolders as bins).",
        "2. Or ask the AI: *\"import a whoosh, a white flash and the warm light leak\"* (bridge running).",
        "3. Overlays and transition clips go on a track **above** the video. Inspector → Composite Mode:",
        "   **Screen** for leaks/flashes/burns/glitch/bokeh/dust, **Overlay** for grain, **Normal** for PNGs with transparency.",
        "4. LUTs: Project Settings → Color Management → Open LUT Folder → copy `.cube` files in → Update Lists.",
        "   PowerGrades: put `.drx` files into `powergrades/` and ask the AI to apply them, or Gallery → right-click → Import.",
        "",
        "## Your own folders",
        "- `powergrades/` downloaded `.drx` grades · `user-sfx/` · `user-footage/` · `user-music/`",
        "",
    ]
    for cat, its in by_cat.items():
        lines += [f"## {cat} ({len(its)})", "", "| File | Use | Tags |", "|---|---|---|"]
        for it in its:
            lines.append(f"| `{it['file']}` | {it['usage']} | {', '.join(it['tags'])} |")
        lines.append("")
    lines.append(SOURCES)
    return "\n".join(lines)
