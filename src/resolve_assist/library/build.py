def library_dir() -> Path:
    return output_dir() / "library"


class _Builder:
    def __init__(self, root: Path, force: bool, log: Callable[[str], None]) -> None:
        self.root, self.force, self.log = root, force, log
        self.items: list[dict] = []
        self.skipped: list[str] = []

    def add(self, category: str, name: str, ext: str, make: Callable[[Path], dict | None],
            tags: list[str], usage: str) -> None:
        rel = Path(category) / f"{name}{ext}"
        path = self.root / rel
        extra: dict = {}
        if self.force or not path.exists():
            path.parent.mkdir(parents=True, exist_ok=True)
            try:
                extra = make(path) or {}
                self.log(f"  + {rel}")
            except Exception as exc:  # one failing asset must not stop the library
                self.skipped.append(f"{rel}: {exc}")
                return
        self.items.append({"id": name, "category": category, "file": str(rel), "tags": tags,
                           "usage": usage, "license": LICENSE, **extra})


def build_library(force: bool = False, log: Callable[[str], None] = lambda s: None) -> dict:
    root = library_dir()
    root.mkdir(parents=True, exist_ok=True)
    b = _Builder(root, force, log)
    t0 = time.time()

    # Sound effects
    for name, (fn, kw, tags, usage) in S.RECIPES.items():
        b.add("sfx", name, ".wav", lambda p, fn=fn, kw=kw: {"seconds": round(S.write_wav(p, fn(**kw)), 2)}, tags, usage)

    # Music beds (30 s, loop-friendly with fades)
    for name, cfg in MUSIC_PRESETS.items():
        b.add("music", f"{name}-30s", ".wav", lambda p, n=name: {"seconds": generate_music(n, 30.0, p)["seconds"],
                                                                  "bpm": MUSIC_PRESETS[n]["bpm"]},
              ["music", name, *cfg["description"].lower().replace(",", "").split()[:4]], cfg["description"])

    # LUTs (each look at full strength; also 50% variants)
    for name, look in LOOKS.items():
        for strength, suffix in ((1.0, ""), (0.5, "-50")):
            b.add("luts", f"{name}{suffix}", ".cube",
                  lambda p, lk=look, st=strength, n=name: LUT3D.from_transform(look_transform(lk, st), 33, title=n).write(p),
                  ["lut", "look", name], look.description + ("" if not suffix else " (half strength)"))

    # Overlays (PNG)
    for pal, colors in LEAK_PALETTES.items():
        for k in (1, 2):
            b.add("overlays", f"light-leak-{pal}-{k}", ".png",
                  lambda p, c=colors, s=k * 7 + len(pal): I.light_leak(p, W, H, s, c),
                  ["light leak", "overlay", pal, "glow"], "Track above clip, Composite Mode: Screen")
    for tint_name, tint in (("warm", (1.0, 0.75, 0.45)), ("cool", (0.55, 0.75, 1.0)), ("pink", (1.0, 0.55, 0.75))):
        b.add("overlays", f"bokeh-{tint_name}", ".png", lambda p, t=tint, n=tint_name: I.bokeh(p, W, H, len(n), t),
              ["bokeh", "overlay", tint_name, "dreamy"], "Composite Mode: Screen, opacity 40-70%")
    for strength, label in ((0.55, "soft"), (0.85, "strong")):
        b.add("overlays", f"vignette-{label}", ".png", lambda p, s=strength: I.vignette(p, W, H, s),
              ["vignette", "overlay", label], "Transparent PNG above the clip (Normal mode)")
    b.add("overlays", "film-grain-still", ".png", lambda p: I.grain(p, W, H, 1, 0.08),
          ["grain", "film", "texture"], "Composite Mode: Overlay, opacity 30-60%")
    b.add("overlays", "dust-scratches", ".png", lambda p: I.dust(p, W, H, 3),
          ["dust", "scratches", "film", "vintage"], "Composite Mode: Screen")
    b.add("overlays", "letterbox-2.39", ".png", lambda p: I.letterbox(p, W, H, 2.39),
          ["letterbox", "cinematic", "bars"], "Transparent PNG on top: instant cinemascope bars")
    b.add("overlays", "lower-third-panel", ".png", lambda p: I.lower_third(p, W, H, (0.95, 0.55, 0.3)),
          ["lower third", "title", "text background"], "Under a Text+ title (names, captions)")

    # Backgrounds (16:9 and 9:16)
    for name, (c1, c2) in GRADIENTS.items():
        b.add("backgrounds", f"gradient-{name}-16x9", ".png", lambda p, a=c1, z=c2: I.gradient(p, W, H, a, z),
              ["background", "gradient", name, "16:9"], "Title cards, end screens")
        b.add("backgrounds", f"gradient-{name}-9x16", ".png", lambda p, a=c1, z=c2: I.gradient(p, H, W, a, z, 60),
              ["background", "gradient", name, "9:16", "vertical"], "Vertical title cards for Reels/TikTok")

    # Transition overlays (video, need ffmpeg)
    if find_ffmpeg():
        b.add("transitions", "flash-white", ".mp4", lambda p: V.flash(p, "white"),
              ["flash", "transition", "white"], "On the cut, Composite Mode: Screen/Add; pair with impact SFX")
        b.add("transitions", "flash-warm", ".mp4", lambda p: V.flash(p, "0xFFB060"),
              ["flash", "transition", "warm"], "Warm flash on the cut (Screen)")
        for pal in ("warm", "pink", "cool", "gold"):
            still = root / "overlays" / f"light-leak-{pal}-1.png"
            b.add("transitions", f"light-leak-sweep-{pal}", ".mp4", lambda p, s=still: V.leak_sweep(p, s),
                  ["light leak", "transition", pal], "Center it on the cut, Composite Mode: Screen")
        b.add("transitions", "film-burn", ".mp4",
              lambda p: V.burn(p, root / "overlays" / "light-leak-warm-2.png"),
              ["burn", "film", "transition", "vintage"], "End/start of scenes, Composite Mode: Screen")
        b.add("transitions", "glitch-burst", ".mp4", lambda p: V.glitch(p),
              ["glitch", "transition", "digital"], "On the cut (Screen, 50-80%); pair with glitch-burst SFX")
        b.add("overlays", "film-grain-10s", ".mp4", lambda p: V.film_grain(p),
              ["grain", "film", "texture", "animated"], "Loop above the edit, Composite Mode: Overlay")
    else:
        b.skipped.append("transitions/*.mp4: ffmpeg not installed (brew install ffmpeg), run again afterwards")

    # User folders (filled by you: downloaded PowerGrades, stock clips, extra SFX) and renders from
    # motion-studio (`npm run make -- <config> --to-resolve`) / Higgsfield downloads.
    for folder in ("powergrades", "user-sfx", "user-footage", "user-music", "motion", "ai-generated"):
        (root / folder).mkdir(exist_ok=True)
    for folder, usage in (("motion", "Rendered in motion-studio. .mov = transparent (ProRes 4444): put on a track above, Normal mode"),
                          ("ai-generated", "Generated with Higgsfield (check credits/terms); use like stock footage/images"),
                          ("powergrades", "PowerGrade: apply with apply_powergrade")):
        for f in sorted((root / folder).iterdir()):
            if f.is_file() and f.suffix.lower() in {".mp4", ".mov", ".png", ".jpg", ".jpeg", ".webp", ".wav", ".mp3", ".drx"}:
                words = [w for w in f.stem.replace("_", "-").split("-") if w and not w.isdigit()]
                alpha = f.suffix.lower() == ".mov"
                b.items.append({"id": f.stem, "category": folder, "file": f"{folder}/{f.name}",
                                "tags": [folder, *words, *(["transparent", "overlay"] if alpha else [])],
                                "usage": usage, "license": "yours (made by you)" if folder != "powergrades" else "see source"})

    manifest = {"generated": time.strftime("%Y-%m-%d %H:%M"), "root": str(root), "items": b.items}
    (root / "manifest.json").write_text(json.dumps(manifest, indent=1), encoding="utf-8")
    (root / "README.md").write_text(_readme(b.items), encoding="utf-8")
    counts: dict[str, int] = {}
    for it in b.items:
        counts[it["category"]] = counts.get(it["category"], 0) + 1
    return {"root": str(root), "counts": counts, "total": len(b.items), "skipped": b.skipped,
            "seconds": round(time.time() - t0, 1)}


def load_manifest() -> dict:
    path = library_dir() / "manifest.json"
    if not path.exists():
        return {"items": []}
    return json.loads(path.read_text(encoding="utf-8"))


def search(query: str = "", category: str | None = None, limit: int = 20) -> list[dict]:
    words = [w for w in query.lower().split() if w]
    out = []
    for it in load_manifest().get("items", []):
        if category and it["category"] != category:
            continue
        hay = " ".join([it["id"], it["category"], it["usage"], *it["tags"]]).lower()
        score = sum(1 for w in words if w in hay)
        if words and score == 0:
            continue
        out.append((score, it))
    out.sort(key=lambda x: -x[0])
    return [it for _, it in out[:limit]]


