def scan_user_folders(root: Path) -> list[dict]:
    items = []
    for folder, category, usage, extra in USER_FOLDERS:
        d = root / folder
        if not d.is_dir():
            continue
        for f in sorted(d.rglob("*") if folder == "fonts" else d.iterdir()):   # fonts sit in family folders
            if f.is_file() and not f.name.startswith(".") and f.suffix.lower() in USER_EXTS:
                words = [w for w in f.stem.replace("_", "-").split("-") if w and not w.isdigit()]
                alpha = f.suffix.lower() == ".mov" and category != "footage"  # motion renders: ProRes 4444
                tags = list(dict.fromkeys([*folder.split("/"), *extra, *words,
                                           *(["transparent", "overlay"] if alpha else [])]))
                items.append({"id": f.stem, "category": category, "file": f.relative_to(root).as_posix(), "tags": tags,
                              "usage": usage, "license": USER_LICENSE.get(folder, "yours (made by you)")})
    return items


def refresh_index() -> dict:
    """Re-scan only the user folders (motion, ai-generated, powergrades, footage/obs) and update the
    manifest. Fast: generates nothing, keeps every generated asset entry as it is."""
    root = library_dir()
    root.mkdir(parents=True, exist_ok=True)
    prefixes = tuple(f"{folder}/" for folder, *_ in USER_FOLDERS)
    kept = [it for it in load_manifest().get("items", []) if not str(it.get("file", "")).startswith(prefixes)]
    user = scan_user_folders(root)
    _write_manifest(root, kept + user)
    return {"root": str(root), "total": len(kept) + len(user), "user_items": len(user)}


def _write_manifest(root: Path, items: list[dict]) -> None:
    manifest = {"generated": time.strftime("%Y-%m-%d %H:%M"), "root": str(root), "items": items}
    (root / "manifest.json").write_text(json.dumps(manifest, indent=1), encoding="utf-8")
    (root / "README.md").write_text(_readme(items), encoding="utf-8")
    from .browser import write_browser
    write_browser(root, items)


def load_manifest() -> dict:
    path = library_dir() / "manifest.json"
    if not path.exists():
        return {"items": []}
    return json.loads(path.read_text(encoding="utf-8"))


def search(query: str = "", category: str | None = None, limit: int = 20) -> list[dict]:
    words = [w for w in query.lower().split() if w]
    out = []
    for it in load_manifest().get("items", []):
        if category and it["category"] != category:
            continue
        hay = " ".join([it["id"], it["category"], it["usage"], *it["tags"]]).lower()
        score = sum(1 for w in words if w in hay)
        if words and score == 0:
            continue
        out.append((score, it))
    out.sort(key=lambda x: -x[0])
    return [it for _, it in out[:limit]]


